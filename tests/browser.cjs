const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { pathToFileURL } = require('node:url');

(async () => {
  const root = path.resolve(__dirname, '..');
  const skill = path.join(root, 'skills', 'editorial-article');
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'editorial-article-browser-'));
  const output = path.join(temporary, 'site');
  const command = process.env.PYTHON_BIN || (process.platform === 'win32' ? 'py' : 'python3');
  const prefix = process.env.PYTHON_BIN ? [] : process.platform === 'win32' ? ['-3'] : [];
  const built = spawnSync(command, [...prefix, path.join(skill, 'scripts', 'render_article.py'), '--brief', path.join(skill, 'assets', 'brief.example.json'), '--out', output], { encoding: 'utf8' });
  if (built.status !== 0) throw new Error(built.stderr || 'Could not launch Python; set PYTHON_BIN.');
  const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH;
  const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const errors = [], remote = [], failed = [];
  const screenshotDir = path.join(root, 'artifacts');
  fs.mkdirSync(screenshotDir, { recursive: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    for (const file of ['index.html', 'pl.html']) {
      const page = await context.newPage();
      page.on('pageerror', error => errors.push(error.message));
      page.on('request', request => { if (/^https?:/.test(request.url())) remote.push(request.url()); });
      page.on('requestfailed', request => failed.push(request.url()));
      await page.goto(pathToFileURL(path.join(output, file)).href);
      await page.evaluate(() => document.fonts.ready);
      await page.waitForFunction(() => [...document.images].every(image => image.complete && image.naturalWidth > 0));
      assert.equal(await page.locator('header, .brand, .language-switch, #print-button').count(), 0);
      assert.equal(await page.locator('.rail li').count(), 3);
      assert.equal(await page.locator('.step').evaluateAll(buttons => buttons.every(button => button.getAttribute('aria-label').includes(button.textContent.trim().replace(/\s+/g, ' ')))), true);
      await page.screenshot({ path: path.join(screenshotDir, file + '-desktop.png') });
      const progressScale = () => page.evaluate(() => { const style = getComputedStyle(document.querySelector('.progress span')).transform; return style === 'none' ? 0 : new DOMMatrix(style).a; });
      assert.equal(await progressScale() < 0.01, true, 'progress starts empty');
      await page.evaluate(() => window.scrollTo({ top: document.body.scrollHeight, behavior: 'instant' }));
      await page.waitForFunction(() => { const style = getComputedStyle(document.querySelector('.progress span')).transform; return style !== 'none' && new DOMMatrix(style).a > 0.99; });
      await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
      await page.waitForFunction(() => { const style = getComputedStyle(document.querySelector('.progress span')).transform; return style !== 'none' && new DOMMatrix(style).a < 0.01; });
      await page.evaluate(() => window.savedStep = document.querySelector('.step'));
      await page.locator('#next-step').click();
      assert.equal(await page.evaluate(() => window.savedStep === document.querySelector('.step')), true);
      assert.equal(await page.locator('#step-count').innerText(), '2 / 3');
      await page.locator('#tab-capture').focus();
      await page.keyboard.press('End');
      assert.equal(await page.locator('#tab-process').getAttribute('aria-selected'), 'true');
      assert.equal(await page.locator('.rail li').count(), 2);
      await page.keyboard.press('Home');
      assert.equal(await page.locator('#tab-capture').getAttribute('aria-selected'), 'true');
      await page.locator('#play-flow').click();
      await page.waitForTimeout(2400);
      assert.equal(await page.locator('#step-count').innerText(), '2 / 3');
      await page.locator('#play-flow').click();
      assert.equal(await page.locator('#play-flow').getAttribute('aria-pressed'), 'false');
      await page.locator('[data-term="queue"]').hover();
      assert.equal(await page.locator('#glossary-tooltip').isVisible(), true);
      await page.keyboard.press('Escape');
      assert.equal(await page.locator('#glossary-tooltip').isVisible(), false);
      await page.locator('[data-node="worker"] circle').click();
      assert.equal(await page.locator('[data-node="worker"]').getAttribute('aria-pressed'), 'true');
      await page.locator('[data-edge="link"]').click();
      assert.equal(await page.locator('.graph-edge.folder').first().evaluate(node => node.style.opacity), '0.1');
      await page.locator('details').nth(0).locator('summary').click();
      await page.locator('details').nth(1).locator('summary').click();
      assert.equal(await page.locator('details[open]').count(), 1);
      assert.equal(await page.locator('details').nth(0).evaluate(node => node.open), false);
      assert.match(await page.locator('details').nth(0).evaluate(node => getComputedStyle(node, '::details-content').transitionProperty), /block-size/);
      assert.equal(await page.locator('.model-chip').count(), 4);
      assert.match(await page.locator('.model-chip').first().getAttribute('rel'), /noopener/);
      await page.locator('#author-button').hover();
      assert.equal(await page.locator('#author-card').isVisible(), true);
      await page.mouse.move(10, 10);
      await page.waitForTimeout(100);
      assert.equal(await page.locator('#author-card').isVisible(), true);
      await page.waitForTimeout(160);
      assert.equal(await page.locator('#author-card').isVisible(), false);
      await page.locator('#author-button').hover();
      await page.locator('#author-card').hover();
      await page.waitForTimeout(240);
      assert.equal(await page.locator('#author-card').isVisible(), true);
      await page.keyboard.press('Escape');
      await page.locator('#author-button').focus();
      await page.keyboard.press('ArrowDown');
      assert.equal(await page.locator('.author-links a').evaluate(node => node === document.activeElement), true);
      await page.keyboard.press('Escape');
      assert.equal(await page.locator('#author-button').evaluate(node => node === document.activeElement), true);
      assert.equal(await page.locator('#author-card').isVisible(), false);
      await page.locator('#play-flow').click();
      await page.emulateMedia({ reducedMotion: 'reduce' });
      await page.waitForFunction(() => document.getElementById('play-flow').getAttribute('aria-pressed') === 'false', undefined, { timeout: 5000 });
      assert.equal(await page.locator('.reveal').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).opacity === '1')), true);
      for (const width of [390, 320]) {
        await page.setViewportSize({ width, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile width ' + width);
        await page.locator('#author-button').click();
        const card = await page.locator('#author-card').boundingBox();
        assert(card.x >= 14 && card.x + card.width <= width - 14);
        await page.keyboard.press('Escape');
      }
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: path.join(screenshotDir, file + '-mobile.png') });
      await page.close();
    }
    const example = await context.newPage();
    example.on('pageerror', error => errors.push(error.message));
    example.on('request', request => { if (/^https?:/.test(request.url())) remote.push(request.url()); });
    await example.goto(pathToFileURL(path.join(skill, 'assets', 'example', 'index.html')).href);
    await example.waitForFunction(() => [...document.images].every(image => image.complete && image.naturalWidth > 0));
    assert.match(await example.locator('.byline').innerText(), /Kacper/);
    assert.equal(await example.locator('header, .brand, .language-switch').count(), 0);
    assert.equal(await example.locator('.progress span').evaluate(node => getComputedStyle(node).transform), 'matrix(0, 0, 0, 1, 0, 0)');
    await example.close();
    const noJS = await browser.newContext({ javaScriptEnabled: false });
    const plain = await noJS.newPage();
    await plain.goto(pathToFileURL(path.join(output, 'index.html')).href);
    assert.equal(await plain.locator('.article section').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).opacity === '1')), true);
    assert.match(await plain.locator('noscript').innerText(), /Receive/);
    await noJS.close();
    assert.deepEqual(errors, []);
    assert.deepEqual(remote, []);
    assert.deepEqual(failed, []);
    console.log(JSON.stringify({ status: 'PASS', languages: ['en', 'pl'], desktop: '1440x1000', mobile: [390, 320], checked: ['offline resources/fonts', 'configurable pipeline length', 'stable button DOM', 'keyboard tabs', 'playback/pause', 'glossary', 'graph and filters', 'exclusive FAQ', 'faq expand/collapse animation', 'model chips', 'reading progress bar', '200ms author handoff', 'keyboard/Escape/focus return', 'mobile panel bounds', 'reduced motion', 'no-JS reading', 'Kacper reference example'], javascriptErrors: errors.length, externalRequests: remote.length, tempDirectory: temporary }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
